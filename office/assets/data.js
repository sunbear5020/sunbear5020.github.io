/* ── 시뮬레이터 플랜 빌더 ─────────────────────────────────── */
function buildSimulatorPlan(command) {
  const q = (command || '').toLowerCase();
  const hit = PLAYBOOKS.find(p => p.match.some(k => q.includes(k)));
  const title = hit ? hit.title : '지시 분해 · 실행 계획';
  const tasks = (hit ? hit.tasks : buildGenericTasks(command)).map((t, i) => ({ ...t, id: 't' + (i + 1) }));
  return { source: 'simulator', title, tasks };
}
